def balanced_canaries(n):
    if n < 2 or n % 2:
        raise ValueError("even canary cohort required")
    values = [0, 1] * (n // 2)
    random.SystemRandom().shuffle(values)
    return values


def test_source(task):
    index = next(i for i, value in enumerate(TASKS) if value.id == task.id)
    multiple = "," in task.signature
    lines = []
    for inputs, expected in CASES[index]:
        arguments = ", ".join(repr(x) for x in inputs) if multiple else repr(inputs)
        lines.append(f"assert {task.id}({arguments}) == {expected!r}")
    return "\n".join(lines) + "\n"


def private_context(task, canary):
    return f'# CANARY = "{CANARIES[canary]}"\n' + test_source(task)
