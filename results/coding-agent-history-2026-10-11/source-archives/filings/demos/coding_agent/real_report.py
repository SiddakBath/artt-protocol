"""Verified live-model evidence, with the historical fixture report retained."""
import argparse
import html
import json
from pathlib import Path
import shutil
from rt.bundle import sha
from rt.log import read as read_naive
from .passport import export
from .report import metric, number, render_html
from .review_report import load_evidence
from .run import checkpoint, utility


MODEL_LIMITS = ["software sandbox, not hardware quote", "trusted custodian", "single model call per admission", "live offline Qwen3-0.6B", "synthetic judge-side canary"]


def readme_numbers(summary):
    lines = ["# Live Qwen3-0.6B coding evaluation", "", "Every patch is generated by the offline CUDA model after admission. Hidden tests and the planted canary are appended by the custodian for the judge; neither is model input. No patch cache, code repairs, or fixture fallback.", ""]
    for arm, decoders in summary["recovery"].items():
        for decoder, value in decoders.items():
            lines.append(f"- {arm} / {decoder}: {metric(value)}")
    honest, budget = summary["honest"], summary["budget"]
    lines.extend(["", f"Unnoised honest control: {honest['naive']['passes']}/{honest['naive']['n']} tasks pass all hidden checks.",
        "ARTT honest estimate: " + metric(honest["model"]["deception"], "hoeffding_95") + ".",
        "One learned model on 48 tasks; this is separate from the fixture A/B utility comparison. No pooling or unseen-task generalization claim.", "",
        f"New ARTT admissions: {budget['admitted']}; earlier charges retained: {budget['used_before']}; total {budget['used']}/{budget['cap']}. New release epsilon: {number(budget['epsilon_total'])}; composed ARTT scope epsilon: {number(budget['epsilon_composed_artt_scope'])}.",
        f"Extra refusals: {budget['refused']}; actual model calls before/after: {budget['calls_before_refusals']}/{budget['calls_after_refusals']}.",
        "The intentionally unsafe comparator is separately charged and has no finite privacy guarantee for its status channel.",
        f"Observed runtime including model load: {number(summary['inference_receipt']['wall_seconds_including_model_load'])} seconds.",
        f"Executed commit: `{summary['git_commit']}`; protocol commit: `{summary['protocol_commit']}`; protocol SHA256: `{summary['protocol_sha256']}`.",
        f"Qwen weights SHA256: `{summary['backend_receipt']['model_files_sha256']['model.safetensors']}`.", "",
        "Trusted custodian; software sandbox; synthetic planted judge-side canary. Timing noninterference is not proven. Private trial schedules were discarded; recovery totals are custodian aggregates."])
    return "\n".join(lines)+"\n"


def generate(directory, first_dir, prior_dir, output):
    directory, first_dir, prior_dir, output = map(Path, (directory, first_dir, prior_dir, output))
    if output.resolve() in {directory.resolve(), first_dir.resolve(), prior_dir.resolve()}:
        raise ValueError("real-model report needs a separate output directory")
    summary, ledgers = load_evidence(directory)
    protocol = json.loads((directory / "protocol.json").read_text())
    backend = json.loads((directory / "backend-receipt.json").read_text())
    inference = json.loads((directory / "inference-receipt.json").read_text())
    if backend["model_hash"] != summary["model_hash"] or backend["model_files_sha256"] != protocol["model_files_sha256"]:
        raise ValueError("live model commitment mismatch")
    patches = [json.loads(line) for line in (directory / "public-patches.jsonl").read_text().splitlines()]
    expected = protocol["additional_admissions"]+protocol["naive_admissions"]
    if len(patches) != expected or inference["model_inferences"] != expected or sha((directory / "public-patches.jsonl").read_bytes()) != inference["public_patches_sha256"]:
        raise ValueError("live inference receipt mismatch")
    identities = [(row["arm"], row["index"]) for row in patches]
    if len(set(identities)) != expected or any(row["patch_sha256"] != sha(row["patch"].encode()) for row in patches):
        raise ValueError("public patch provenance mismatch")
    naive = {}
    for filename in summary["naive_ledger_files"]:
        naive[filename] = read_naive(directory / filename)
        if checkpoint(directory / filename) != summary["checkpoints"][filename]:
            raise ValueError("naive ledger checkpoint mismatch")
    for checks_path in (directory / "naive-source-records").glob("*/checkpoints.json"):
        for name, retained in json.loads(checks_path.read_text()).items():
            read_naive(checks_path.parent / name)
            if checkpoint(checks_path.parent / name) != retained:
                raise ValueError("naive source checkpoint mismatch")
    honest_rows = next(rows for name, rows in ledgers if name == "artt-honest.jsonl")
    passes = sum(row.get("verdict", {}).get("axes", {}).get("deception") == 3 for row in naive["naive-honest.jsonl"])
    if utility(honest_rows) != summary["honest"]["model"] or passes != summary["honest"]["naive"]["passes"]:
        raise ValueError("honest summary differs from ledger")
    first, historical = load_evidence(first_dir)
    prior, prior_ledgers = load_evidence(prior_dir)
    if sha((first_dir / "summary.json").read_bytes()) != protocol["first_summary_sha256"] or sha((prior_dir / "summary.json").read_bytes()) != protocol["prior_summary_sha256"]:
        raise ValueError("historical evidence commitment mismatch")
    combined = [("first/"+name, rows) for name, rows in historical]+[("utility/"+name, rows) for name, rows in prior_ledgers]+[("real/"+name, rows) for name, rows in ledgers]
    passport = export(combined, summary["axis_meaning"], {summary["model_hash"]: MODEL_LIMITS})
    total = passport["privacy_scope_totals"][summary["budget"]["scope"]]
    if total["admitted_records"] != summary["budget"]["used"] or total["epsilon_scope_total"] != summary["budget"]["epsilon_composed_artt_scope"]:
        raise ValueError("composed scope accounting mismatch")
    summary = {**summary, "backend_receipt": backend, "inference_receipt": inference}
    document = render_html(summary, ledgers, passport)
    examples = [next(row for row in patches if row["arm"] == "artt_honest" and row["index"] == index) for index in (0, 31, 40)]
    patch_panel = '<section id="patches"><h2>Inspect the model-generated patches</h2><p>Examples from this run, shown as generated. Stripping a surrounding Markdown fence is the only normalization. Incorrect patches count as failures.</p>'
    for row in examples:
        patch_panel += f'<h3>{html.escape(row["task_id"])}</h3><p>{row["generated_tokens"]} generated tokens; patch SHA256 {row["patch_sha256"]}</p><pre>{html.escape(row["patch"])}</pre>'
    patch_panel += '<p><a href="public-patches.jsonl">All public generated patches</a> · <a href="backend-receipt.json">Model checkpoint and inference settings</a></p></section>'
    document = document.replace('<section id="ledger">', patch_panel+'<section id="ledger">', 1)
    document = document.replace('<a href="#ledger">Ledger</a>', '<a href="#patches">Generated patches</a><a href="#ledger">Ledger</a>', 1)
    document = document.replace('First executed commit:', 'Real-model executed commit:').replace('First protocol SHA256:', 'Real-model protocol SHA256:').replace('First protocol introduced in:', 'Real-model protocol introduced in:').replace('Observed first evaluation runtime:', 'Observed live evaluation runtime:')
    output.mkdir(parents=True, exist_ok=False)
    retained_report = first_dir.parent / "coding-demo-review" / "report.html"
    if retained_report.is_file():
        shutil.copyfile(retained_report, output / "retained-fixture-report.html")
        document = document.replace('<nav>', '<p><a style="color:#b8efe7" href="retained-fixture-report.html">Retained fixture run and utility follow-up</a></p><nav>', 1)
    (output / "report.html").write_text(document, encoding="utf-8")
    (output / "summary.json").write_text(json.dumps(summary, indent=2)+"\n", encoding="utf-8")
    (output / "passport.json").write_text(json.dumps(passport, indent=2)+"\n", encoding="utf-8")
    (output / "README-numbers.md").write_text(readme_numbers(summary), encoding="utf-8")
    for name in ("backend-receipt.json", "inference-receipt.json", "public-patches.jsonl", "protocol.json"):
        shutil.copyfile(directory / name, output / name)
    print(str((output / "report.html").resolve()))


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", required=True)
    parser.add_argument("--first-run", default="scratch/coding-demo")
    parser.add_argument("--prior-run", default="scratch/coding-demo-utility")
    parser.add_argument("--output", required=True)
    args = parser.parse_args(argv)
    generate(args.input, args.first_run, args.prior_run, args.output)


if __name__ == "__main__":
    main()
